const pluralRules = new Map();

// Picks a word form for a number: forms are listed in CLDR order (ru: one|few|many, de/en: one|other).
function pluralForm(lang, value, forms) {
  if (!pluralRules.has(lang)) pluralRules.set(lang, new Intl.PluralRules(lang));
  const number = Math.abs(Number(value));
  const category = Number.isFinite(number) ? pluralRules.get(lang).select(number) : "other";
  const order = lang === "ru" ? ["one", "few", "many"] : ["one", "other"];
  const index = Math.min(Math.max(order.indexOf(category), category === "other" ? order.length - 1 : 0), forms.length - 1);
  return forms[index];
}

// Placeholders: {name} inserts the value; {name:form1|form2|...} inserts only the right word form for it.
export function t(lang, key, params = {}) {
  const table = STRINGS[lang] || STRINGS.en;
  const template = table[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)(?::([^}]*))?\}/g, (match, name, forms) => {
    if (!(name in params)) return match;
    return forms === undefined ? String(params[name]) : pluralForm(lang, params[name], forms.split("|"));
  });
}